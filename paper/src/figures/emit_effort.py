"""Effort per model at the default budget, over every session on record:
sessions played, the median number of actions in a session, the keys sent per
action and the median time between two actions. Prints tables/effort.tex;
preflight.py writes it.
"""
import os
import statistics as st
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import field  # noqa: E402
from display_names import display_agent

rows = field.played(field.load_runs(dedup=False))
models = field.model_rows([r for r in rows if not field.is_random(r["agent"])])
floor = field.model_rows([r for r in rows if field.is_random(r["agent"])])
models.sort(key=field.ladder_order)
by = {}
for r in rows:
    by.setdefault(r["agent"], []).append(r)


def line(m):
    rs = by[m["agent"]]
    acts = [r["actions"] for r in rs]
    gaps = [r.get("gap_p50") for r in rs]
    if any(g is None for g in gaps) or any(r.get("key_events") is None for r in rs):
        sys.exit(f"{m['agent']}: a session lacks its key count or the gap between actions")
    keys = sum(r["key_events"] for r in rs)
    return "\\texttt{%s} & %d & %.0f & %.1f & %.0f \\\\" % (
        display_agent(m["agent"]), len(rs), st.median(acts), keys / sum(acts), st.median(gaps))


print("% generated by figures/emit_effort.py from the field records; do not hand-edit")
print("\\begin{tabular}{@{}lrrrr@{}}")
print("\\toprule")
print("Model & Sessions & Actions per session & Keys per action & Seconds between actions \\\\")
print("\\midrule")
for m in models:
    print(line(m))
print("\\midrule")
for m in floor:
    print(line(m))
print("\\bottomrule")
print("\\end{tabular}")
