"""The four-hour sessions that count, one row per session with its identifier:
the minute of the last key, the actions sent, the minute at which each
milestone was first reached, and the milestones credited. Prints
tables/long.tex; preflight.py writes it.
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import field
import long_cohort

COLUMNS = (("Map", "crossing"), ("Item", "obtained"), ("Scene", "scene"),
           ("Hermit", "hermit"), ("Compass", "compass"), ("Companion", "recruited"))


def minute_text(minute):
    if minute is None:
        return "--"
    if minute < 1:
        return "$<1$"
    return "%.1f" % minute


def first_minute(events, name):
    if name == "recruited":
        return events.get("recruited_minute")
    if name == "scene":
        return (events.get("scenes") or {}).get("first_minute")
    minutes = (events.get(name) or {}).get("minutes")
    return minutes[0] if minutes else None


def main():
    rows = field.load_long()
    if not rows:
        sys.exit("no four-hour session counts")
    rows.sort(key=lambda r: (-field.rungs_reached(r), r["agent"]))
    print("% generated by figures/emit_long.py from the four-hour sessions that count; do not hand-edit")
    print("\\begin{tabular}{@{}ll" + "r" * (3 + len(COLUMNS)) + "@{}}")
    print("\\toprule")
    print("Model & Session & Last key & Actions & " + " & ".join(c for c, _ in COLUMNS) + " & Milestones \\\\")
    print("\\midrule")
    for r in rows:
        e = r.get("replay")
        if not e:
            sys.exit("no replay reading for " + r["id"])
        cells = []
        for _, name in COLUMNS:
            minute = (r["exit_secs"] / 60 if r.get("exit_secs") is not None else None) if name == "crossing" else first_minute(e, name)
            cells.append(minute_text(minute))
        print("\\texttt{%s} & \\texttt{%s} & %s & %d & %s & %d \\\\" % (
            r["agent"], r["id"], minute_text(long_cohort.last_key_seconds(r) / 60),
            r["actions"], " & ".join(cells), field.rungs_reached(r)))
    print("\\bottomrule")
    print("\\end{tabular}")


if __name__ == "__main__":
    main()
